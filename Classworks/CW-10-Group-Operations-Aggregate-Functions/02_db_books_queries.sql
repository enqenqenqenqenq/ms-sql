-- =====================================================================
-- ЧАСТЬ 1. АГРЕГАТНЫЕ ФУНКЦИИ (COUNT, SUM, AVG, MIN, MAX)
-- =====================================================================

-- 1.1. Функция COUNT: Подсчитать общее количество книг в каталоге
SELECT COUNT(*) AS [Общее количество книг]
FROM Books;

-- 1.2. Функция COUNT с полем: Подсчитать количество оформленных продаж
SELECT COUNT(Code_purchase) AS [Количество сделок]
FROM Purchases;

-- 1.3. Функция SUM: Подсчитать общее количество проданных экземпляров книг
SELECT SUM(Amount) AS [Всего продано экземпляров]
FROM Purchases;

-- 1.4. Функция SUM: Подсчитать общую сумму выручки от всех продаж
SELECT SUM(Cost * Amount) AS [Общая сумма выручки, руб.]
FROM Purchases;

-- 1.5. Функция AVG: Вычислить средний объем книги (в страницах)
SELECT AVG(Pages) AS [Средний объем книги (стр.)]
FROM Books;

-- 1.6. Функция AVG: Вычислить среднюю стоимость одной сделки
SELECT AVG(Cost * Amount) AS [Средний чек сделки, руб.]
FROM Purchases;

-- 1.7. Функции MIN и MAX: Определить минимальную и максимальную цену книги при продажах
SELECT 
    MIN(Cost) AS [Минимальная цена, руб.],
    MAX(Cost) AS [Максимальная цена, руб.]
FROM Purchases;

-- 1.8. Функции MIN и MAX по дате: Найти дату первой и последней зафиксированной продажи
SELECT 
    MIN(Date_order) AS [Первая продажа],
    MAX(Date_order) AS [Крайняя продажа]
FROM Purchases;
GO

-- =====================================================================
-- ЧАСТЬ 2. ГРУППОВЫЕ ОПЕРАЦИИ (GROUP BY)
-- =====================================================================

-- 2.1. Группировка по одному полю:
-- Посчитать количество книг, выпущенных каждым издательством
SELECT 
    Code_publish AS [Код издательства],
    COUNT(Code_book) AS [Количество книг]
FROM Books
GROUP BY Code_publish;

-- 2.2. Группировка по одному полю:
-- Для каждого доставщика рассчитать общее число доставленных книг и общую сумму
SELECT 
    Code_delivery AS [Код доставщика],
    SUM(Amount) AS [Доставлено экземпляров],
    SUM(Cost * Amount) AS [Сумма заказов, руб.]
FROM Purchases
GROUP BY Code_delivery;

-- 2.3. Группировка по нескольким полям:
-- Сгруппировать продажи по коду книги и типу оплаты (нал/безнал),
-- вывести суммарный объем продаж
SELECT 
    Code_book AS [Код книги],
    Type_purchase AS [Тип оплаты],
    SUM(Amount) AS [Продано шт.],
    SUM(Cost * Amount) AS [Сумма, руб.]
FROM Purchases
GROUP BY Code_book, Type_purchase;

-- 2.4. Группировка по нескольким полям:
-- Посчитать число заказов по каждому доставщику и каждой книге
SELECT 
    Code_delivery AS [Код доставщика],
    Code_book AS [Код книги],
    COUNT(*) AS [Количество заказов],
    SUM(Amount) AS [Всего книг]
FROM Purchases
GROUP BY Code_delivery, Code_book;
GO

-- =====================================================================
-- ЧАСТЬ 3. ПРЕДЛОЖЕНИЕ HAVING (ФИЛЬТРАЦИЯ ГРУПП)
-- =====================================================================

-- 3.1. Найти издательства, у которых среднее число страниц в книгах превышает 300
SELECT 
    Code_publish AS [Код издательства],
    AVG(Pages) AS [Среднее кол-во страниц],
    COUNT(Code_book) AS [Количество наименований]
FROM Books
GROUP BY Code_publish
HAVING AVG(Pages) > 300;

-- 3.2. Вывести доставщиков, суммарный объем доставок которых превысил 15 экземпляров
SELECT 
    Code_delivery AS [Код доставщика],
    SUM(Amount) AS [Суммарный тираж]
FROM Purchases
GROUP BY Code_delivery
HAVING SUM(Amount) > 15;

-- 3.3. Найти книги, выручка от продаж которых составила более 5000 рублей
SELECT 
    Code_book AS [Код книги],
    SUM(Cost * Amount) AS [Выручка по книге, руб.]
FROM Purchases
GROUP BY Code_book
HAVING SUM(Cost * Amount) > 5000;
GO

-- =====================================================================
-- ЧАСТЬ 4. УПОРЯДОЧЕНИЕ ВЫВОДА (ORDER BY)
-- =====================================================================

-- 4.1. Простая сортировка:
-- Вывести список издательств, отсортированный по городам, а внутри города — по названию
SELECT City, Publish
FROM Publishing_house
ORDER BY City ASC, Publish ASC;

-- 4.2. Совместное использование GROUP BY и ORDER BY:
-- Вывести суммарный объем продаж по каждой книге с сортировкой по убыванию выручки
SELECT 
    Code_book AS [Код книги],
    SUM(Amount) AS [Продано экземпляров],
    SUM(Cost * Amount) AS [Общая выручка, руб.]
FROM Purchases
GROUP BY Code_book
ORDER BY [Общая выручка, руб.] DESC;

-- 4.3. Комплексный запрос: GROUP BY + HAVING + ORDER BY
-- Вывести доставщиков с общей суммой заказов свыше 3000 руб., отсортировав по коду доставщика
SELECT 
    Code_delivery AS [Код доставщика],
    COUNT(Code_purchase) AS [Число заказов],
    SUM(Cost * Amount) AS [Итоговая сумма, руб.]
FROM Purchases
GROUP BY Code_delivery
HAVING SUM(Cost * Amount) > 3000
ORDER BY Code_delivery ASC;
GO
