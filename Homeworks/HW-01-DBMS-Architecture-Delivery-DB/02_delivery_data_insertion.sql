-- Сводный запрос: проверка связей между таблицами
SELECT 
    d.НомерДоговора,
    d.ДатаДоговора,
    p.КодПоставщика,
    COALESCE(fl.Фамилия + ' ' + fl.Имя + ' ' + fl.Отчество, ul.Наименование) AS [Поставщик],
    pos.Товар,
    pos.Количество,
    pos.Цена,
    (pos.Количество * pos.Цена) AS [Сумма]
FROM dbo.Договоры AS d
JOIN dbo.Поставщики AS p ON d.КодПоставщика = p.КодПоставщика
LEFT JOIN dbo.ФизическиеЛица AS fl ON p.КодПоставщика = fl.КодПоставщика
LEFT JOIN dbo.ЮридическиеЛица AS ul ON p.КодПоставщика = ul.КодПоставщика
JOIN dbo.Поставлено AS pos ON d.НомерДоговора = pos.НомерДоговора
ORDER BY d.НомерДоговора, pos.Товар;
GO
