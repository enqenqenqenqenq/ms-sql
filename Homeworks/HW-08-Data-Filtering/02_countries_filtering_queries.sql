-- Пример 1: Список стран Европы
SELECT Название, Столица, Площадь, Население, Континент
FROM dbo.Страны
WHERE Континент = N'Европа';
GO

-- Пример 2: Страны с площадью не менее 1 млн. кв. км
SELECT Название, Столица, Площадь, Население, Континент
FROM dbo.Страны
WHERE Площадь >= 1000000;
GO

-- Пример 3: Европейские страны с населением более 10 млн. чел.
SELECT Название, Столица, Площадь, Население, Континент
FROM dbo.Страны
WHERE (Континент = N'Европа') AND (Население > 10000000);
GO

-- Пример 4: Страны с населением более 100 млн. чел. или площадью более 1 млн. кв. км
SELECT Название, Столица, Площадь, Население, Континент
FROM dbo.Страны
WHERE (Население > 100000000) OR (Площадь > 1000000);
GO

-- Пример 5: Страны с площадью более 1 млн. кв. км, не расположенные в Африке
SELECT Название, Столица, Площадь, Население, Континент
FROM dbo.Страны
WHERE NOT (Континент = N'Африка') AND (Площадь > 1000000);
GO

-- Пример 6: Европейские страны с населением > 10 млн или азиатские страны с населением > 50 млн
SELECT Название, Столица, Площадь, Население, Континент
FROM dbo.Страны
WHERE (Континент = N'Европа') AND (Население > 10000000)
   OR (Континент = N'Азия') AND (Население > 50000000);
GO

-- Пример 7: Страны с населением от 10 до 100 млн и площадью от 100 до 200 тыс. кв. км
SELECT Название, Столица, Площадь, Население, Континент
FROM dbo.Страны
WHERE (Население BETWEEN 10000000 AND 100000000)
  AND (Площадь >= 100000) AND (Площадь <= 200000);
GO

-- Пример 8: Отсортированный список стран от Бенина до Ватикана
SELECT Название, Столица, Площадь, Население, Континент
FROM dbo.Страны
WHERE Название BETWEEN N'Бенин' AND N'Ватикан'
ORDER BY Название;
GO

-- Пример 9: Страны на букву «С»
SELECT Название, Столица, Площадь, Население, Континент
FROM dbo.Страны
WHERE Название LIKE N'С%';
GO

-- Пример 10: Страны со второй буквой «а» и последней «я»
SELECT Название, Столица, Площадь, Население, Континент
FROM dbo.Страны
WHERE Название LIKE N'_а%я';
GO

-- Пример 11: Страны с третьей буквой «а», «о» или «у»
SELECT Название, Столица, Площадь, Население, Континент
FROM dbo.Страны
WHERE Название LIKE N'__[аоу]%';
GO

-- Пример 12: Страны, начинающиеся на буквы от «А» до «Г»
SELECT Название, Столица, Площадь, Население, Континент
FROM dbo.Страны
WHERE Название LIKE N'[А-Г]%';
GO

-- Пример 13: Страны, не начинающиеся на буквы от «А» до «Г» и не с буквы «С»
SELECT Название, Столица, Площадь, Население, Континент
FROM dbo.Страны
WHERE Название LIKE N'[^А-Г,^С]%';
GO

-- Пример 14: Страны, столицы которых не введены в базу (NULL)
SELECT Название, Столица, Площадь, Население, Континент
FROM dbo.Страны
WHERE Столица IS NULL;
GO

-- Пример 15: Список европейских, азиатских и африканских стран
SELECT Название, Столица, Площадь, Население, Континент
FROM dbo.Страны
WHERE Континент IN (N'Европа', N'Азия', N'Африка');
GO


