-- Создание базы данных, если отсутствует
IF NOT EXISTS (SELECT * FROM sys.databases WHERE name = 'DB_COUNTRIES')
BEGIN
    CREATE DATABASE DB_COUNTRIES;
END
GO

USE DB_COUNTRIES;
GO

-- Удаление таблицы перед повторным созданием
IF OBJECT_ID('dbo.Страны', 'U') IS NOT NULL DROP TABLE dbo.Страны;
GO

-- Создание таблицы «Страны»
CREATE TABLE dbo.Страны (
    Название NVARCHAR(60) PRIMARY KEY NOT NULL,
    Столица NVARCHAR(60) NULL,
    Площадь BIGINT NOT NULL,
    Население BIGINT NOT NULL,
    Континент NVARCHAR(40) NOT NULL
);
GO

